a = "python"
print(a[::-1])  #//The slicing syntax [::-1] is used to reverse a string in Python. It creates a new string that is a reversed version of the original string by slicing it with a step of -1, which means it starts from the end and moves backwards through the string.
# Output: nohtyp    
print(a)  # Output: python (the original string remains unchanged)

a = [1, 2, 3, 4, 5]
a.reverse()  #//The reverse() method is used to reverse the order of elements in a list. It modifies the original list by reversing the order of its elements in place.
print(a)  # Output: [5, 4, 3, 2, 1]


